import { colors, type ColorTokens } from './colors.js';
import { density, fontFamily, radius } from './scale.js';

const toKebab = (s: string) => s.replace(/([a-z])([A-Z0-9])/g, '$1-$2').toLowerCase();

function block(selector: string, vars: Record<string, string>, scheme?: 'light' | 'dark'): string {
  const lines = Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`);
  if (scheme) lines.push(`  color-scheme: ${scheme};`);
  return `${selector} {\n${lines.join('\n')}\n}`;
}

function colorVars(c: ColorTokens): Record<string, string> {
  return Object.fromEntries(Object.entries(c).map(([k, v]) => [toKebab(k), v]));
}

/**
 * Builds the CSS custom-property stylesheet consumed by the web app.
 * - `:root` = light theme; `.dark` on <html> = dark theme.
 * - `[data-density]` on <html> switches control/row sizing.
 */
export function buildCssVariables(): string {
  const shared = {
    'radius-sm': `${radius.sm}px`,
    'radius-md': `${radius.md}px`,
    'radius-lg': `${radius.lg}px`,
    'radius-xl': `${radius.xl}px`,
    'font-sans': fontFamily.sans,
    'font-mono': fontFamily.mono,
  };
  const d = (mode: keyof typeof density) => ({
    'control-h': `${density[mode].control}px`,
    'row-h': `${density[mode].row}px`,
    'density-gap': `${density[mode].gap}px`,
  });

  return [
    '/* Generated by @hrm/design-tokens. Do not edit by hand. */',
    block(':root', { ...shared, ...colorVars(colors.light), ...d('compact') }, 'light'),
    block('.dark', colorVars(colors.dark), 'dark'),
    block('[data-density="comfortable"]', d('comfortable')),
    block('[data-density="compact"]', d('compact')),
    '',
  ].join('\n\n');
}
